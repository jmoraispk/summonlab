const ARRAY_INDEX = '(?:0|[1-9]\\d*)';
const RETIRED_ARMOR = deriveRetiredForms('armor')[0]!;
const RETIRED_OCHER = deriveRetiredForms('ocher')[0]!;

function exactPointerPattern(pointer: string): RegExp {
	const source = pointer
		.split('/')
		.map((component) =>
			component === '*' ? ARRAY_INDEX : component.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&')
		)
		.join('/');
	return new RegExp(`^${source}$`, 'u');
}

